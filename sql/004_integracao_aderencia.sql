-- Executar somente após conferir o esquema e as políticas (docs/integracao-aderencia.md).
-- Transacional: incompatibilidade com tabela legada provoca rollback, nunca apaga dados.
begin;
-- CREATE TABLE IF NOT EXISTS não valida tabelas legadas. Não inferir vínculos
-- de currículos existentes: vaga_id deve ter sido criada/preenchida pela equipe.
do $$
declare missing text;
begin
  select string_agg(t.tab || '.' || t.col, ', ') into missing
  from (values ('curriculos','id'), ('curriculos','vaga_id'),
               ('vagas','id'), ('vagas','criado_por'),
               ('usuarios','id'), ('usuarios','auth_user_id')) t(tab,col)
  where not exists (select 1 from information_schema.columns c
    where c.table_schema='public' and c.table_name=t.tab and c.column_name=t.col);
  if missing is not null then
    raise exception 'Pré-requisito ausente: %. Confira docs/integracao-aderencia.md; não atribua vagas arbitrariamente.', missing;
  end if;
  if exists (select 1 from information_schema.columns c
      where c.table_schema='public' and c.table_name='curriculos'
        and c.column_name in ('id','vaga_id')
        and c.udt_name not in ('int2','int4','int8')) then
    raise exception 'curriculos.id e curriculos.vaga_id devem ser inteiros compatíveis com o vínculo de vagas. Confira o esquema legado.';
  end if;
end $$;
alter table public.curriculos add column if not exists content_hash text;
create unique index if not exists curriculos_content_uidx
  on public.curriculos(vaga_id, content_hash) where content_hash is not null;
create unique index if not exists curriculos_vaga_id_uidx on public.curriculos(vaga_id, id);

-- Se já existir, preserva todas as linhas/colunas legadas.
create table if not exists public.analises_aderencia (
  id bigint generated by default as identity primary key
);
alter table public.analises_aderencia
  add column if not exists vaga_id bigint references public.vagas(id),
  add column if not exists curriculo_id bigint references public.curriculos(id),
  add column if not exists requirements_hash text,
  add column if not exists text_hash text,
  add column if not exists config_hash text,
  add column if not exists result jsonb,
  add column if not exists ner_model text,
  add column if not exists embedding_model text,
  add column if not exists formula_version text,
  add column if not exists weights jsonb,
  add column if not exists pipeline_version text,
  add column if not exists pontuacao_aderencia double precision,
  -- Se já existir como timestamp sem fuso, preserva tipo, default e valores.
  add column if not exists analisado_em timestamptz default now();
-- A coluna legada float8 mantém seus valores. Incompletas passam a usar SQL NULL.
-- Nenhum UPDATE/backfill ou substituição de pontuações legadas é realizado.
alter table public.analises_aderencia alter column pontuacao_aderencia drop not null;
alter table public.analises_aderencia alter column pontuacao_aderencia drop default;
do $$
declare incompatible text;
begin
  select string_agg(t.col || ' (esperado ' || t.typ || ')', ', ') into incompatible
  from (values ('result','jsonb'), ('pontuacao_aderencia','float8'),
       ('requirements_hash','text'), ('text_hash','text'), ('config_hash','text'),
       ('ner_model','text'), ('embedding_model','text'), ('formula_version','text'),
       ('weights','jsonb'), ('pipeline_version','text'), ('analisado_em','timestamp ou timestamptz')) t(col,typ)
  where not exists (select 1 from information_schema.columns c
    where c.table_schema='public' and c.table_name='analises_aderencia'
      and c.column_name=t.col
      and (c.udt_name=t.typ or
           (t.col='analisado_em' and c.udt_name in ('timestamp','timestamptz'))));
  if incompatible is not null then
    raise exception 'Tabela analises_aderencia legada incompatível: %. Confira o esquema antes de migrar.', incompatible;
  end if;
  if (select count(*) from information_schema.columns c
      where c.table_schema='public' and c.table_name='analises_aderencia'
        and c.column_name in ('id','vaga_id','curriculo_id')
        and c.udt_name in ('int2','int4','int8')) <> 3 then
    raise exception 'analises_aderencia deve possuir id, vaga_id e curriculo_id inteiros compatíveis. CREATE TABLE IF NOT EXISTS não valida tabela legada.';
  end if;
end $$;
-- NOT VALID permite preservar dados antigos; novas gravações sempre são verificadas.
do $$
begin
  if not exists (select 1 from pg_constraint
      where conrelid='public.analises_aderencia'::regclass
        and conname='aderencia_curriculo_vaga_fk') then
    alter table public.analises_aderencia add constraint aderencia_curriculo_vaga_fk
      foreign key (vaga_id, curriculo_id) references public.curriculos(vaga_id, id) not valid;
  end if;
end $$;
-- Substitui apenas a CHECK deste pacote para também corrigir sua versão anterior.
alter table public.analises_aderencia drop constraint if exists aderencia_novos_resultados_ck;
alter table public.analises_aderencia add constraint aderencia_novos_resultados_ck check (
 (vaga_id is not null and curriculo_id is not null and requirements_hash is not null
  and text_hash is not null and config_hash is not null and result is not null
  and ner_model is not null and embedding_model is not null
  and formula_version is not null and weights is not null and pipeline_version is not null
  and case when jsonb_typeof(result) = 'object'
                 and result ? 'status' and result ? 'score' then
    case result->>'status'
      when 'calculado' then
        case when jsonb_typeof(result->'score') = 'number' then
          case when (result->>'score')::numeric between 0 and 100 then
            pontuacao_aderencia is not null
            and pontuacao_aderencia = (result->>'score')::double precision
          else false end
        else false end
      when 'analise_incompleta' then
        result->'score' = 'null'::jsonb and pontuacao_aderencia is null
      else false
    end
  else false end) is true
) not valid;
create unique index if not exists aderencia_version_uidx on public.analises_aderencia
  (vaga_id, curriculo_id, requirements_hash, text_hash, config_hash);

alter table public.curriculos enable row level security;
alter table public.analises_aderencia enable row level security;
revoke all on public.curriculos, public.analises_aderencia from anon;
grant select, insert, update on public.curriculos, public.analises_aderencia to authenticated;
-- Descobre sequences de serial/identity sem presumir seus nomes. IDs podem
-- também usar um mecanismo sem sequence; nesse caso não há grant a fazer.
do $$
declare seq_name text; table_name text;
begin
  foreach table_name in array array['public.curriculos', 'public.analises_aderencia'] loop
    seq_name := pg_get_serial_sequence(table_name, 'id');
    if seq_name is not null then
      execute format('grant usage, select on sequence %s to authenticated', seq_name::regclass);
    end if;
  end loop;
end $$;

-- Restritivas impedem políticas permissivas preexistentes de ampliar o acesso.
-- Recria somente as quatro políticas deste pacote, preservando as demais.
drop policy if exists aderencia_owner_guard on public.analises_aderencia;
drop policy if exists aderencia_owner_access on public.analises_aderencia;
drop policy if exists curriculos_owner_guard on public.curriculos;
drop policy if exists curriculos_owner_access on public.curriculos;
create policy aderencia_owner_guard on public.analises_aderencia as restrictive
  for all to authenticated
  using (vaga_id in (select v.id from public.vagas v join public.usuarios u on u.id=v.criado_por where u.auth_user_id=auth.uid()))
  with check (vaga_id in (select v.id from public.vagas v join public.usuarios u on u.id=v.criado_por where u.auth_user_id=auth.uid()));
create policy aderencia_owner_access on public.analises_aderencia for all to authenticated
  using (true) with check (true);
create policy curriculos_owner_guard on public.curriculos as restrictive
  for all to authenticated
  using (vaga_id in (select v.id from public.vagas v join public.usuarios u on u.id=v.criado_por where u.auth_user_id=auth.uid()))
  with check (vaga_id in (select v.id from public.vagas v join public.usuarios u on u.id=v.criado_por where u.auth_user_id=auth.uid()));
create policy curriculos_owner_access on public.curriculos for all to authenticated
  using (true) with check (true);
commit;
